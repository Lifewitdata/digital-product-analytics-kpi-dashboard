def pdf_literal(i):
    depth, out, i = 1, bytearray(), i + 1
    while i < len(blob_pdf) and depth:
        c = blob_pdf[i]
        if c == 0x5C:
            nxt = blob_pdf[i + 1:i + 2]
            if nxt.isdigit():
                digits = blob_pdf[i + 1:i + 4]
                k = 0
                while k < len(digits) and digits[k:k + 1].isdigit():
                    k += 1
                out.append(int(digits[:k], 8))
                i += 1 + k
                continue
            mapping = {0x28: b"(", 0x29: b")", 0x5C: b"\\", 0x6E: b" ", 0x72: b" ", 0x74: b" "}
            out += mapping.get(nxt, nxt)
            i += 2
            continue
        if c == 0x28:
            depth += 1
        elif c == 0x29:
            depth -= 1
            if not depth:
                return bytes(out), i + 1
        out.append(c)
        i += 1
    return bytes(out), i


