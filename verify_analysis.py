def check(label, ok, detail=""):
    global passed, failed
    if ok:
        passed += 1
    else:
        failed += 1
        print(f"  FAIL  {label}" + (f"   [{detail}]" if detail else ""))


def close(label, got, want, tol=5e-4):
    check(label, bool(np.isclose(got, want, rtol=0, atol=tol)), f"{got:g} vs {want:g}")


def prose(path, text):
    """Whitespace-normalised substring test, so README line-wrapping is irrelevant."""
    blob = re.sub(r"\s+", " ", (BASE / path).read_text(encoding="utf-8"))
    check(f"{path} states {text!r}", re.sub(r"\s+", " ", text) in blob)


